import { readFile, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generatedBanner = "/* Generated by tools/build-media-demo.mjs. Do not edit by hand. */";
const globalPath = path.join(root, "phosphor/media-renderer.global.js");
const singleHtmlPath = path.join(root, "磷光矩阵媒体处理单文件版.html");

const librarySources = [
  "phosphor/renderer/config.js",
  "phosphor/renderer/utils.js",
  "phosphor/renderer/source-sampler.js",
  "phosphor/renderer/webgl/gl-utils.js",
  "phosphor/renderer/webgl/shader-sources.js",
  "phosphor/renderer/webgl/webgl-pipeline.js",
  "phosphor/media-renderer.js",
];

function stripModuleSyntax(source, file) {
  let code = source
    .replace(/^import\s+[\s\S]*?;\s*$/gm, "")
    .replace(/^export\s+\{[\s\S]*?\}\s+from\s+["'][^"']+["'];?\s*$/gm, "")
    .replace(/^export\s+\{[\s\S]*?\};?\s*$/gm, "")
    .replace(/\bexport\s+(class|function|const|let|var)\s+/g, "$1 ");

  if (file.endsWith("media-renderer.js")) {
    code = code.replace(/function isVideoElement/, "function isMediaRendererVideoElement");
    code = code.replace(/return isVideoElement\(source\)/, "return isMediaRendererVideoElement(source)");
  }

  assertNoModuleSyntax(code, file);
  return code.trim();
}

function assertNoModuleSyntax(code, label) {
  const leftovers = code.match(/(^|\n)\s*(import|export)\s+/);
  if (leftovers) {
    throw new Error(`Module syntax remains after transforming ${label}: ${leftovers[0].trim()}`);
  }
}

async function readProjectFile(relativePath) {
  return readFile(path.join(root, relativePath), "utf8");
}

function normalizeLineEndings(value) {
  return value.replace(/\r\n?/g, "\n");
}

function indentNonEmptyLines(value, indent = "  ") {
  return value
    .split("\n")
    .map((line) => (line ? `${indent}${line}` : ""))
    .join("\n");
}

async function buildGlobalLibrary() {
  const parts = [];
  for (const file of librarySources) {
    const source = normalizeLineEndings(await readProjectFile(file));
    parts.push(`\n// ${file}\n${stripModuleSyntax(source, file)}`);
  }

return `${generatedBanner}
(function () {
  "use strict";
${indentNonEmptyLines(parts.join("\n"))}

  window.Phosphor = {
    PHOSPHOR_DEFAULT_CONFIG,
    createPhosphorConfig,
    PhosphorMediaRenderer,
  };
}());
`;
}

function inlineDemoScripts(html, libraryCode, demoCode) {
  const inlined = html
    .replace(/\s*<script src="phosphor\/media-renderer\.global\.js"><\/script>/, `\n  <script>\n${libraryCode}\n  </script>`)
    .replace(/\s*<script src="test\/phosphor-media-demo\.js"><\/script>/, `\n  <script>\n${demoCode}\n  </script>`);
  if (inlined === html || /<script\s+src="(?:phosphor|test\/)/.test(inlined)) {
    throw new Error("Failed to inline demo scripts into the single HTML file.");
  }
  return inlined;
}

function verifyGeneratedFiles(libraryCode, singleHtml) {
  assertNoModuleSyntax(libraryCode, "phosphor/media-renderer.global.js");
  execFileSync(process.execPath, ["--check", globalPath], { stdio: "pipe" });
  if (/src="(?:phosphor|test\/)/.test(singleHtml)) {
    throw new Error("Single HTML still references external phosphor/test scripts.");
  }
}

const libraryCode = await buildGlobalLibrary();

const html = normalizeLineEndings(await readProjectFile("media-demo.html"));
const demoCode = normalizeLineEndings(await readProjectFile("test/phosphor-media-demo.js"));
const singleHtml = `<!-- Generated by tools/build-media-demo.mjs. Do not edit by hand. -->\n${inlineDemoScripts(html, libraryCode, demoCode)}`;
verifyGeneratedFiles(libraryCode, singleHtml);

await writeFile(globalPath, libraryCode, "utf8");
await writeFile(singleHtmlPath, singleHtml, "utf8");

console.log("Generated phosphor/media-renderer.global.js");
console.log("Generated 磷光矩阵媒体处理单文件版.html");
